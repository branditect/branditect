/**
 * Write branditect-ui/spec/i18n-gap-site.md: every string on the public site
 * that still renders in English on /fi, grouped by file.
 *
 * The site half of scripts/i18n-gap.mjs, with the same scanner. Two lists:
 * strings with no key at all, which are the translator's, and strings whose
 * English matches a key but are still hard-coded, which are the build side's
 * (the key exists, the file does not read it).
 *
 * Usage: npm run i18n:gap:site
 */
import { writeFileSync } from "node:fs";
import { siteGap } from "../lib/i18n-site-gap.ts";
import { en } from "../lib/i18n/en.ts";

const { unkeyed, unwired, unread } = siteGap();
const count = (sections) => sections.reduce((n, s) => n + s.rows.length, 0);

const lines = [
  "# The marketing site strings that have no key",
  "",
  "Generated by `npm run i18n:gap:site`. Do not edit by hand. Regenerate it.",
  "",
  "Everything below renders in English on `/fi`, `/fi/pricing` or `/fi/about`.",
  "`FI_COPY_READY` (lib/site-locale.ts) cannot go true until this file is empty:",
  "a test in lib/site-locale.test.ts runs the same scan.",
  "",
  `**${count(unkeyed)} strings with no key, across ${unkeyed.length} files.**`,
  "Each is the whole string as it appears; `{name}` marks a value filled in at",
  "runtime, and belongs in the key as a placeholder. Nothing here is truncated.",
  "",
];
for (const { f, rows } of unkeyed) {
  lines.push(`## ${f}`, "", ...rows.map((r) => `- ${r.replace(/\|/g, "\\|")}`), "");
}
lines.push("---", "", `## Has a key, still hard-coded (${count(unwired)})`, "",
  "Build side, not translation: the English matches a key that the file does not read.", "");
if (!unwired.length) lines.push("None.", "");
for (const { f, rows } of unwired) {
  lines.push(`### ${f}`, "", ...rows.map((r) => `- ${r.replace(/\|/g, "\\|")}`), "");
}

lines.push("---", "", `## Keys nothing on the site reads (${unread.length})`, "",
  "A key here is usually a string that was cut short when it was extracted, so it",
  "cannot be rendered without gluing English onto it, or one a whole-sentence key",
  "replaced. Compare its English with the full string in the list above.", "");
if (!unread.length) lines.push("None.", "");
for (const k of unread) lines.push(`- \`${k}\`: ${en[k].replace(/\|/g, "\\|")}`);
lines.push("");

writeFileSync("branditect-ui/spec/i18n-gap-site.md", lines.join("\n"));
console.log(`${count(unkeyed)} unkeyed, ${count(unwired)} keyed but hard-coded → branditect-ui/spec/i18n-gap-site.md`);
